"""Publish the painted NPC walk strips.

assets/images/characters/npc_walk already holds an 8-frame walk for every
facing. Rebuilding those frames from the standing pose smears the staff,
the hem and the shoes, and that is what the game was playing.

This copies the painted strips into npc_cycle, writes a 4-frame idle from
the contact pose, and records how far the body should travel per cycle.
Side-view foot separation, two steps:
  chief 93, fun 83, queen 70 source px.
Those numbers must match NpcFrames.STRIDE_BY_SHEET.
"""

from __future__ import annotations

import shutil
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = ROOT / "assets/images/characters/npc_walk"
OUT_DIR = ROOT / "assets/images/characters/npc_cycle"
FRAME_DIR = OUT_DIR / "frames"
PREVIEW_DIR = ROOT / "tools/preview"
META_PATH = ROOT / "scripts/world/npc_stride_meta.gd"
FRAME_W, FRAME_H = 256, 192
CYCLE_FRAMES = 8
CHARACTERS = ["chief", "fun", "queen"]
DIRS = ["down", "down_right", "right", "up_right", "up"]
STRIDE_BY_SHEET = {"chief": 93.0, "fun": 83.0, "queen": 70.0}
IDLE_DY = (0, -1, -1, 0)


def write_meta() -> None:
    lines = [
        "# AUTO-GENERATED by tools/build_npc_walk_sheets.py. Do not edit.",
        "class_name NpcStrideMeta",
        "extends RefCounted",
        "",
        f"const FRAMES_PER_CYCLE := {CYCLE_FRAMES}",
        "## Source px the body travels per full cycle (two steps), per character.",
        "## Measured from the painted side-view foot separation.",
        "const STRIDE_BY_SHEET := {",
    ]
    for name in CHARACTERS:
        lines.append(f'\t"{name}": {STRIDE_BY_SHEET[name]:.1f},')
    lines.append("}")
    META_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def slice_strip(path: Path) -> list[Image.Image]:
    img = Image.open(path).convert("RGBA")
    count = img.width // FRAME_W
    if count < 1 or img.width != count * FRAME_W or img.height != FRAME_H:
        raise SystemExit(f"{path.name} is {img.size}, expected {FRAME_W * CYCLE_FRAMES}x{FRAME_H}")
    return [img.crop((i * FRAME_W, 0, (i + 1) * FRAME_W, FRAME_H)) for i in range(count)]


def shift_y(frame: Image.Image, dy: int) -> Image.Image:
    if dy == 0:
        return frame.copy()
    out = Image.new("RGBA", frame.size, (0, 0, 0, 0))
    out.paste(frame, (0, dy), frame)
    return out


def save_strip(frames: list[Image.Image], path: Path) -> None:
    strip = Image.new("RGBA", (FRAME_W * len(frames), FRAME_H), (0, 0, 0, 0))
    for i, frame in enumerate(frames):
        strip.paste(frame, (i * FRAME_W, 0), frame)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.stem + ".tmp.png")
    strip.save(tmp)
    try:
        tmp.replace(path)
    except OSError:
        strip.save(path)
        if tmp.exists():
            tmp.unlink(missing_ok=True)


def save_contact(sheet_id: str, dir_name: str, walk: list[Image.Image], idle: list[Image.Image]) -> None:
    cells = walk + idle
    sheet = Image.new("RGBA", (FRAME_W * len(cells), FRAME_H), (0, 0, 0, 0))
    for i, frame in enumerate(cells):
        sheet.paste(frame, (i * FRAME_W, 0), frame)
    draw = ImageDraw.Draw(sheet)
    draw.line([(0, 180), (sheet.width - 1, 180)], fill=(255, 40, 40, 220), width=1)
    for i in range(len(cells)):
        x = i * FRAME_W + 128
        draw.line([(x, 0), (x, FRAME_H - 1)], fill=(40, 220, 80, 220), width=1)
    PREVIEW_DIR.mkdir(parents=True, exist_ok=True)
    sheet.save(PREVIEW_DIR / f"{sheet_id}_{dir_name}.png")


def build_dir(sheet_id: str, dir_name: str) -> None:
    src = SRC_DIR / f"{sheet_id}_{dir_name}.png"
    if not src.exists():
        print(f"skip missing {src.name}", flush=True)
        return
    walk = slice_strip(src)
    if len(walk) != CYCLE_FRAMES:
        raise SystemExit(f"{src.name} has {len(walk)} frames, expected {CYCLE_FRAMES}")
    dest = OUT_DIR / f"{sheet_id}_{dir_name}.png"
    dest.parent.mkdir(parents=True, exist_ok=True)
    try:
        shutil.copy2(src, dest)
    except OSError:
        save_strip(walk, dest)
    FRAME_DIR.mkdir(parents=True, exist_ok=True)
    for i, frame in enumerate(walk):
        try:
            frame.save(FRAME_DIR / f"{sheet_id}_{dir_name}_{i + 1:02d}.png")
        except OSError:
            pass
    idle = [shift_y(walk[0], dy) for dy in IDLE_DY]
    save_strip(idle, OUT_DIR / f"{sheet_id}_{dir_name}_idle.png")
    save_contact(sheet_id, dir_name, walk, idle)
    print(f"copied {sheet_id}_{dir_name} painted walk", flush=True)


def main() -> None:
    print("publishing painted npc strips", flush=True)
    write_meta()
    for sheet_id in CHARACTERS:
        for dir_name in DIRS:
            build_dir(sheet_id, dir_name)


if __name__ == "__main__":
    main()
